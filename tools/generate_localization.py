#!/usr/bin/env python3
"""Build deterministic C# display dictionaries from confirmed translation CSVs."""
import csv,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def load(name):
 with (ROOT/'translation'/name).open(encoding='utf-8-sig',newline='') as f:return list(csv.DictReader(f))
terms=load('01_game_terms.csv');ui=load('03_ui_text_candidates.csv');game=load('02_game_data_ids.csv')
texts={};enums={};bykey={row['key']:row for row in terms}
for row in terms+ui:
 if not row['zh_CN']:continue
 if row['key'].startswith('enum.'):
  enums[row['key'][5:]]=row['zh_CN'];continue
 if row['original'] in texts and texts[row['original']]!=row['zh_CN']:raise ValueError(f"Conflicting display translation: {row['original']}")
 texts[row['original']]=row['zh_CN']
def term(original):return next(row['zh_CN'] for row in terms if row['original']==original and row['zh_CN'])
aliases={
 'DutyType.Unknown':'Unknown','DutyType.CrystallineConflict':'Crystalline Conflict',
 'CrystallineConflictTeamName.Unknown':'Unknown','CrystallineConflictTeamName.Astra':'Astra','CrystallineConflictTeamName.Umbra':'Umbra',
 'CrystallineConflictMatchType.Unknown':'Unknown',
 'CrystallineConflictMap.Palaistra':'The Palaistra','CrystallineConflictMap.VolcanicHeart':'The Volcanic Heart','CrystallineConflictMap.CloudNine':'Cloud Nine','CrystallineConflictMap.ClockworkCastleTown':'Clockwork Castletown','CrystallineConflictMap.RedSands':'The Red Sands','CrystallineConflictMap.BaysideBattleground':'Bayside Battleground','CrystallineConflictMap.ArcheiaHarmonias':'Archeia Harmonias',
 'CrystallineConflictMatchEvent.CrystalUnchained':'The crystal has been unchained.','CrystallineConflictMatchEvent.OvertimeCommenced':'Overtime has started.'}
for tier in ['Bronze','Silver','Gold','Platinum','Diamond','Crystal']:aliases['ArenaTier.'+tier]=tier.lower()
for abbr,name in zip('PLD WAR DRK GNB MNK DRG NIN SAM RPR VPR WHM SCH AST SGE BRD MCH DNC BLM SMN RDM PCT'.split(),['Paladin','Warrior','Dark Knight','Gunbreaker','Monk','Dragoon','Ninja','Samurai','Reaper','Viper','White Mage','Scholar','Astrologian','Sage','Bard','Machinist','Dancer','Black Mage','Summoner','Red Mage','Pictomancer']):aliases['Job.'+abbr]=name
for typ,roles in {'JobRole':[('TANK','Tank'),('HEALER','Healer'),('DPS','DPS')], 'JobSubRole':[('TANK','Tank'),('HEALER','Healer'),('MELEE','Melee'),('RANGED','Ranged'),('CASTER','Caster')]}.items():
 for role,name in roles:aliases[typ+'.'+role]=name
for key,original in aliases.items():enums.setdefault(key,term(original))
# UI layout copy is authored separately from the user's game glossary.
layout=json.loads((ROOT/'translation/ui-layout.zh-CN.json').read_text())
for original,translated in layout.items():
 if original in texts and texts[original]!=translated:raise ValueError(f"UI copy conflicts with confirmed translation: {original}")
 texts[original]=translated
actions={int(row['row_id']):row['zh_CN'] for row in game if row['sheet']=='Action' and row['zh_CN']}
statuses={int(row['row_id']):row['zh_CN'] for row in game if row['sheet']=='Status' and row['zh_CN']}
def literal(s):return json.dumps(s,ensure_ascii=False)
lines=['// <auto-generated />','// Source: user-confirmed translation CSVs. Run python3 tools/generate_localization.py.','using System.Collections.Generic;','','namespace PvpStats.Localization;','','public static partial class ChineseText {']
for field,kind,values in [('Texts','string',texts),('EnumNames','string',enums),('Actions','uint',actions),('Statuses','uint',statuses)]:
 lines.append(f'    private static readonly Dictionary<{kind}, string> {field} = new() {{')
 for key,value in sorted(values.items()):lines.append(f'        [{literal(key) if isinstance(key,str) else str(key)+"u"}] = {literal(value)},')
 lines.append('    };')
lines.append('}')
(ROOT/'PvpStats/Localization/ChineseText.g.cs').write_text('\n'.join(lines)+'\n')
print(f'Generated: {len(texts)} text, {len(enums)} enum, {len(actions)} action, {len(statuses)} status translations.')
